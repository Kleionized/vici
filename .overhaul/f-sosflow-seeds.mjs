#!/usr/bin/env node
/**
 * sos-flow — writes the urge hub's init seeds (one per pane where the frames
 * contradict each other, sos-flow Q13/Q14), each frozen on one moment with
 * `.overhaul/clock.js` so a capture is the same tomorrow as today.
 *
 *   node .overhaul/f-sosflow-seeds.mjs
 *
 * Moment: Fri 25 Jul 2025, 20:00 (local). Every seed signs in a mock "Jerry".
 *
 *   sosflow-hub-seed.js        85A, 85B, 85C, 85F — a live urge 2:18 old at
 *                              severity 6 ("strong"); slips 21 and 10 days back
 *                              (85B's grid index 8 and 19); 23 ridden out, the
 *                              twelve newest at 85C's own bar heights (s = h ·
 *                              25.625, so the longest is exactly 41 min) at
 *                              severity 4, and an older severity-6 urge of 40 min
 *                              (85B: "None this strong has lasted past forty
 *                              minutes.").
 *   sosflow-hub-surfed-seed.js 85D — the four newest on the frame's own days and
 *                              times, 14 · 22 · 9 · 31 min, the first with no
 *                              `whatHelped` (it reads the default).
 *   sosflow-hub-pledge-seed.js 85E — the pledge signed 14 days back, no slip since.
 */
import fs from 'node:fs';

const CLOCK = '2025-07-25T20:00';
const NOW = new Date(2025, 6, 25, 20, 0, 0).getTime();
const MIN = 60000;
const DAY = 86400000;
const uid = 'sosflow-hub-user';
const clock = fs.readFileSync('.overhaul/clock.js', 'utf8');

function base() {
  return {
    user: { clerkUserId: uid, displayName: 'Jerry', createdAt: NOW - 60 * DAY, onboardingComplete: true, settings: { showStreak: false } },
    progress: {},
    reflections: {},
    lifeMap: { userId: uid, values: [], whyStatement: 'The mornings are mine again.', updatedAt: NOW - 60 * DAY },
    events: [],
    checkins: {},
    journalEntries: [],
  };
}

let n = 0;
const ev = (type, at, extra = {}) => ({ _id: `sf-${type}-${(n += 1)}`, userId: uid, type, createdAt: Math.round(at), ...extra });
const pledge = (at) => ({ _id: 'sf-pledge', userId: uid, tag: 'Pledge', title: 'Today’s pledge', body: 'The mornings are mine again.', createdAt: at });

function write(file, data, session) {
  const lines = [
    `/* GENERATED by .overhaul/f-sosflow-seeds.mjs — the urge hub's account at ${CLOCK}. */`,
    `window.__CLOCK = '${CLOCK}';`,
    clock,
    `localStorage.setItem('tideline.mock.users', ${JSON.stringify(JSON.stringify({ 'seed@vici.app': { userId: uid, email: 'seed@vici.app', password: 'x', displayName: 'Jerry' } }))});`,
    `localStorage.setItem('tideline.session.userId', '${uid}');`,
    `localStorage.setItem('tideline.mock.userdata.${uid}', ${JSON.stringify(JSON.stringify(data))});`,
    session
      ? `localStorage.setItem('tideline.urgeSession', ${JSON.stringify(JSON.stringify(session))});`
      : `localStorage.removeItem('tideline.urgeSession');`,
  ];
  fs.writeFileSync(file, lines.join('\n') + '\n');
  console.log('wrote', file);
}

/** A live urge 2:18 old — 85A's 17:42 of the twenty-minute window — at severity 6. */
const live = { id: 'urge_sosflow', startedAt: NOW - 138000, lastActiveAt: NOW, severity: 6, peakSeverity: 6, reopens: 0, phase: 'active' };

// ── 85A / 85B / 85C / 85F ──
{
  const d = base();
  d.events.push(ev('lapse', NOW - 21 * DAY - 3 * 60 * MIN));
  d.events.push(ev('lapse', NOW - 10 * DAY - 2 * 60 * MIN));
  const HEIGHTS = [29, 39, 23, 56, 35, 96, 27, 46, 20, 33, 65, 29]; // oldest → newest
  HEIGHTS.forEach((h, i) => {
    // the twelve newest, one every 18 hours back from yesterday
    const at = NOW - (HEIGHTS.length - i) * 18 * 60 * MIN;
    d.events.push(ev('urge_rode_out', at, { severity: 4, durationSeconds: h * 25.625 }));
  });
  // eleven older ones, severity 6, the longest of them 40 minutes
  for (let i = 0; i < 11; i += 1) d.events.push(ev('urge_rode_out', NOW - (12 + i) * DAY, { severity: 6, durationSeconds: i === 3 ? 2400 : 480 + i * 60 }));
  d.journalEntries.push(pledge(NOW - 14 * DAY));
  write('.overhaul/sosflow-hub-seed.js', d, live);
}

// ── 85D ──
{
  const d = base();
  const at = (day, h, m) => new Date(2025, 6, day, h, m).getTime();
  const four = [
    [at(24, 15, 10), 14, undefined],
    [at(22, 23, 48), 22, 'Went for a walk'],
    [at(20, 21, 22), 9, 'Called a friend'],
    [at(19, 1, 5), 31, 'Took a cold shower'],
  ];
  for (const [t, min, helped] of four) d.events.push(ev('urge_rode_out', t, { severity: 4, durationSeconds: min * 60, ...(helped ? { whatHelped: helped } : {}) }));
  for (let i = 0; i < 6; i += 1) d.events.push(ev('urge_rode_out', NOW - (8 + i) * DAY, { severity: 4, durationSeconds: 600 }));
  d.journalEntries.push(pledge(NOW - 14 * DAY));
  write('.overhaul/sosflow-hub-surfed-seed.js', d, live);
}

// ── 85E ──
{
  const d = base();
  d.events.push(ev('lapse', NOW - 20 * DAY));
  for (let i = 0; i < 5; i += 1) d.events.push(ev('urge_rode_out', NOW - (2 + i) * DAY, { severity: 4, durationSeconds: 600 }));
  d.journalEntries.push(pledge(NOW - 14 * DAY));
  write('.overhaul/sosflow-hub-pledge-seed.js', d, live);
}
