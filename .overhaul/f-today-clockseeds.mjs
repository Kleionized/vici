#!/usr/bin/env node
/**
 * GROUP today (Phase 1) — the frozen-clock capture accounts for the seven
 * Today / Score frames, built from `.overhaul/today-seed.js` (day 41, 1,240,
 * Navigator II, delta 18, mood 3 / energy 2, the Pledge entry, Jerry) and
 * `.overhaul/clock.js` (OQ-X1: the frames read Friday 18 July 2025).
 *
 * Each file = `window.__CLOCK=…` + clock.js + today-seed.js + a fix-up that
 * runs after the seed wrote its account:
 *   - the account opens at local midnight 40 days back, so the day count is 41
 *     at any hour (the seed's own createdAt is 09:09, which reads day 40 at the
 *     frame's 09:00);
 *   - per frame, the state of today's row.
 *
 *   node .overhaul/f-today-clockseeds.mjs
 */
import fs from 'node:fs';

const clock = fs.readFileSync('.overhaul/clock.js', 'utf8');
const seed = fs.readFileSync('.overhaul/today-seed.js', 'utf8');

const fix = (days, today) => `
(() => {
  const k = 'tideline.mock.userdata.today-seed-user';
  const d = JSON.parse(localStorage.getItem(k));
  const M = new Date().setHours(0, 0, 0, 0);
  d.user.createdAt = M - ${days} * 86400000;
  const key = (ms) => { const x = new Date(ms); return x.getFullYear() + '-' + String(x.getMonth() + 1).padStart(2, '0') + '-' + String(x.getDate()).padStart(2, '0'); };
  const t = key(M);
  d.checkins[t] = Object.assign({}, d.checkins[t], ${JSON.stringify(today)});
  localStorage.setItem(k, JSON.stringify(d));
})();
`;

const files = {
  // Today Home, Score Detail ×3 — morning, task open
  'today-0900-seed.js': ['2025-07-18T09:00', 40, {}],
  // Today Home II — the night check-in named today's action (the generic register)
  'today-ii-seed.js': ['2025-07-18T09:00', 40, { dailyAction: 'Put your phone somewhere hard to reach before you sleep.' }],
  // Today Home Task — lesson 1's task, named and done. The night check-in names
  // the day's lesson task (D236), and a named lesson task keeps its lesson's
  // register (D232); on day 41 the app itself would have named lesson 40's —
  // the frame pairs day 41 with lesson 1, so the seed names lesson 1's.
  'today-task-seed.js': ['2025-07-18T09:00', 40, { dailyAction: 'Put the device you use for porn out of reach before you sleep.', dailyActionDone: true }],
  // the same register reached the app's own way: a day-1 account, lesson 1 by day (flame 1, the week before it open)
  'today-task-d1-seed.js': ['2025-07-18T09:00', 0, { dailyActionDone: true }],
  // Today Home III — evening, the night check-in filed (today's disc fills)
  'today-2000-seed.js': ['2025-07-18T20:00', 40, { emotions: ['Calm', 'Tired'], reasons: ['School / work', 'Loneliness'] }],
};
for (const [file, [at, days, today]] of Object.entries(files)) {
  fs.writeFileSync('.overhaul/' + file, `/* GENERATED by .overhaul/f-today-clockseeds.mjs — do not hand-edit. */\nwindow.__CLOCK = '${at}';\n${clock}\n${seed}\n${fix(days, today)}`);
  console.log('.overhaul/' + file);
}
