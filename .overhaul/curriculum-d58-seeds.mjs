#!/usr/bin/env node
/**
 * curriculum (Phase 2, D339) — capture accounts for the longest task sentence.
 *
 * `task.cardSummary` is now the first sentence of each lesson's own task; the
 * longest is L58's (196 characters). These seeds put the three screens that draw
 * the sentence on it, so a capture shows whether it wraps cleanly and clears the
 * controls under it. Each is a frame's own seed with the day moved to 58:
 *
 *   curriculum-d58-today-seed.js    today-ii-seed.js's account (clock Fri 18 Jul
 *                                   2025 09:00, today-seed.js) opened 57 days back,
 *                                   no action named — page two falls back to the
 *                                   day's lesson, L58, in the lesson register, undone
 *   curriculum-d58-night-seed.js    day-seed.js / vday-seed-d1.js opened 57 days
 *                                   back — Night's action step reads lessonForDay(58)
 *   curriculum-d58-morning-seed.js  the same account, yesterday's row naming L58's
 *                                   sentence — Morning Task Check asks after it
 *
 * The sentence is read out of the generated `src/content/curriculum84.ts`, so a
 * regeneration is picked up by re-running this file.
 *
 *   node .overhaul/curriculum-d58-seeds.mjs
 */
import fs from 'node:fs';

const DAY_N = 58;
const src = fs.readFileSync('src/content/curriculum84.ts', 'utf8');
const at = src.indexOf(`\n        day: ${DAY_N},\n`);
const sentence = at >= 0 && JSON.parse(src.slice(at).match(/cardSummary: ("(?:[^"\\]|\\.)*")/)[1]);
if (!sentence) throw new Error(`no cardSummary for day ${DAY_N}`);

const clock = fs.readFileSync('.overhaul/clock.js', 'utf8');
const todaySeed = fs.readFileSync('.overhaul/today-seed.js', 'utf8');
const daySeed = fs.readFileSync('.overhaul/day-seed.js', 'utf8');

const HEAD = '/* GENERATED by .overhaul/curriculum-d58-seeds.mjs — do not hand-edit. */\n';
const back = DAY_N - 1;

// Today: f-today-clockseeds.mjs's fix-up, day 58, today's row left as the seed has it (no dailyAction).
const today = `${HEAD}window.__CLOCK = '2025-07-18T09:00';
${clock}
${todaySeed}
(() => {
  const k = 'tideline.mock.userdata.today-seed-user';
  const d = JSON.parse(localStorage.getItem(k));
  const M = new Date().setHours(0, 0, 0, 0);
  d.user.createdAt = M - ${back} * 86400000;
  const key = (ms) => { const x = new Date(ms); return x.getFullYear() + '-' + String(x.getMonth() + 1).padStart(2, '0') + '-' + String(x.getDate()).padStart(2, '0'); };
  const t = key(M);
  if (d.checkins[t]) { delete d.checkins[t].dailyAction; d.checkins[t].dailyActionDone = false; }
  localStorage.setItem(k, JSON.stringify(d));
})();
`;

const created = 'createdAt: midnight - 12 * DAY,';
if (!daySeed.includes(created)) throw new Error('day-seed.js no longer opens the account 12 days back');
const night = HEAD + daySeed.replace(created, `createdAt: midnight - ${back} * DAY,`);

const named = "dailyAction: 'Write down each trigger the moment you notice it.'";
if (!daySeed.includes(named)) throw new Error("day-seed.js no longer names yesterday's action");
const morning = HEAD + daySeed.replace(created, `createdAt: midnight - ${back} * DAY,`).replace(named, `dailyAction: ${JSON.stringify(sentence)}`);

for (const [file, body] of [['curriculum-d58-today-seed.js', today], ['curriculum-d58-night-seed.js', night], ['curriculum-d58-morning-seed.js', morning]]) {
  fs.writeFileSync(`.overhaul/${file}`, body);
  console.log(`.overhaul/${file}`);
}
console.log(`L${DAY_N} (${sentence.length}): ${sentence}`);
