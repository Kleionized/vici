// The place drawings `91B · Urge Overview — Scrolled` draws in its Where card
// (Bedroom, Desk, Bathroom: the frame's own art, in the SOS drawings' 40 44 312
// 184 frame), written to src/content/overviewArt.ts.
//
//   node scripts/vici-ui-2/gen-overview-art.mjs
import fs from 'node:fs';
import { unPaintOrder } from './svg.mjs';

const html = fs.readFileSync('Vici UI 2/project/Email Login.dc.html', 'utf8');
const at = html.indexOf('<div data-screen-label="Urge Overview Scrolled"');
const frame = html.slice(at, html.indexOf('<div data-screen-label=', at + 10));
const where = frame.slice(frame.indexOf('>Where<'));
const names = ['Bedroom', 'Desk', 'Bathroom'];
const art = {};
for (const name of names) {
  const end = where.indexOf(`>${name}<`);
  const before = where.slice(0, end);
  const m = [...before.matchAll(/<svg width="100%" height="48" viewBox="40 44 312 184"[^>]*>([\s\S]*?)<\/svg>/g)].pop();
  if (!m) throw new Error(`no drawing for ${name}`);
  art[name.toLowerCase()] = unPaintOrder(m[1]);
}
const body = `// Generated by scripts/vici-ui-2/gen-overview-art.mjs from \`Vici UI 2/project/Email Login.dc.html\` (91B). Do not edit by hand.

/** The Where card's place drawings, as SVG inner markup in the frame \`40 44 312 184\`. */
export const OVERVIEW_PLACE_ART: Record<'bedroom' | 'desk' | 'bathroom', string> = ${JSON.stringify(art, null, 1)};

export const OVERVIEW_ART_VIEWBOX = '40 44 312 184';
`;
fs.writeFileSync('src/content/overviewArt.ts', body);
console.log('src/content/overviewArt.ts', Object.keys(art).map((k) => `${k} ${art[k].length}`).join(', '));
