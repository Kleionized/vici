// Writes VICI_UI_2_REPORT.md: the run's hand-written sections
// (specs/vici-ui-2/report-notes.md, in order, each `## ` heading kept) around
// the tables only the ledger, the decisions file and the inventory can give —
// every screen with its design file, app file, status, final diff and
// side-by-side; every decision with its reasoning; every file in `Vici UI 2`
// with a tick.
//
//   node scripts/vici-ui-2/report.mjs
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';

const ledger = JSON.parse(fs.readFileSync('scripts/vici-ui-2/ledger.json', 'utf8'));
const notes = fs.readFileSync('specs/vici-ui-2/report-notes.md', 'utf8');
const decisions = fs.readFileSync('VICI_UI_2_DECISIONS.md', 'utf8');
const inventory = fs.readFileSync('specs/vici-ui-2/inventory.md', 'utf8');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');

const pctOf = (row) => {
  const j = `pixel-diff/out/${row.id}.json`;
  if (!fs.existsSync(j)) return null;
  return JSON.parse(fs.readFileSync(j, 'utf8')).pct;
};
const sideOf = (row) => (fs.existsSync(`pixel-diff/out/${row.id}.side.png`) ? `pixel-diff/out/${row.id}.side.png` : '—');

const byStatus = {};
for (const r of ledger.rows) byStatus[r.status] = (byStatus[r.status] ?? 0) + 1;

const table = [
  '| row | design file · artboard | app file | status | final diff | side-by-side | note |',
  '|---|---|---|---|---|---|---|',
  ...ledger.rows.map((r) => {
    const p = pctOf(r);
    return `| \`${r.id}\` | ${esc(r.file)} · ${esc(r.label ?? r.screen)} | ${r.app ? `\`${esc(r.app)}\`` : '—'} | ${r.status} | ${p == null ? '—' : `${p.toFixed(3)} %`} | ${sideOf(r) === '—' ? '—' : `\`${sideOf(r)}\``} | ${esc(r.note)} |`;
  }),
];

const branch = execFileSync('git', ['rev-parse', '--abbrev-ref', 'HEAD']).toString().trim();
const head = execFileSync('git', ['rev-parse', '--short', 'HEAD']).toString().trim();

const out = [
  '# VICI UI 2 — report',
  '',
  `Generated by \`scripts/vici-ui-2/report.mjs\` from the ledger (\`scripts/vici-ui-2/ledger.json\`), \`VICI_UI_2_DECISIONS.md\`, \`specs/vici-ui-2/inventory.md\` and the run's notes. Branch \`${branch}\` at \`${head}\`.`,
  '',
  `Ledger: ${Object.entries(byStatus).map(([k, v]) => `${v} ${k}`).join(' · ')} (${ledger.rows.length} rows).`,
  '',
  notes.trim(),
  '',
  '## Every screen',
  '',
  'Each artboard of `Vici UI 2` is a row. The final diff is the share of device pixels that differ (pixelmatch, threshold 0.1, status bar and home indicator excluded, D2); the side-by-side is design | app | mask.',
  '',
  ...table,
  '',
  '## Every decision, with its reasoning',
  '',
  decisions.replace(/^# .*\n/, '').trim(),
  '',
  '## Every file in `Vici UI 2`',
  '',
  inventory.replace(/^# .*\n/, '').trim(),
  '',
];
fs.writeFileSync('VICI_UI_2_REPORT.md', out.join('\n'));
console.log(`VICI_UI_2_REPORT.md: ${ledger.rows.length} rows`);
