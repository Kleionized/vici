// Generates src/content/relapse.data.ts from `Vici UI 2/project/Vici Relapse.dc.html`
// (its MSG, QUOTES, ART, WHEN, CAUSES and WATCH tables) and the calendar drawing
// from lesson-viz-v5.js, so the relapse flow's words and pictures are the bundle's.
//
//   node scripts/vici-ui-2/gen-relapse.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import { unPaintOrder } from './svg.mjs';

const DIR = 'Vici UI 2/project';
const html = fs.readFileSync(`${DIR}/Vici Relapse.dc.html`, 'utf8');
const script = html.slice(html.indexOf('const MSG = ['), html.indexOf('class Component'));
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(`${script}; this.out = { MSG, QUOTES, ART, WHEN, CAUSES, WATCH, CAL_BOX };`, ctx);
vm.runInContext(fs.readFileSync(`${DIR}/lesson-viz-v5.js`, 'utf8'), ctx);
const o = ctx.out;
const j = (v) => JSON.stringify(v, null, 2);
fs.writeFileSync(
  'src/content/relapse.data.ts',
  `// Generated by scripts/vici-ui-2/gen-relapse.mjs from \`Vici UI 2/project/Vici Relapse.dc.html\` and \`lesson-viz-v5.js\`. Do not edit by hand.\n\n` +
    `/** The 48 encouragement messages: id, theme, the facts it needs, the words. */\n` +
    `export const RELAPSE_MESSAGES: [string, string, string[], string][] = ${j(o.MSG)};\n\n` +
    `/** The quotes a message can end on: id, words, author, the themes it goes with ('*' any), the facts it needs. */\n` +
    `export const RELAPSE_QUOTES: [string, string, string, string[], string[]][] = ${j(o.QUOTES)};\n\n` +
    `/** Each theme's drawings (SOS_VIZ keys), taken in turn by the message's place in its theme. */\n` +
    `export const RELAPSE_ART: Record<string, string[]> = ${j(o.ART)};\n\n` +
    `export const RELAPSE_WHEN = ${j(o.WHEN)} as const;\n\n` +
    `export const RELAPSE_CAUSES = ${j(o.CAUSES)} as const;\n\n` +
    `export const RELAPSE_WATCH = ${j(o.WATCH)} as const;\n\n` +
    `/** \`01 · When\`'s calendar drawing (lesson-viz-v5 \`calendar\`) and the box it is shown through. */\n` +
    `export const RELAPSE_CALENDAR = { viewBox: ${JSON.stringify(o.CAL_BOX)}, markup: ${JSON.stringify(unPaintOrder(ctx.window.LESSON_VIZ_V5.calendar))} };\n`,
);
console.log(o.MSG.length, 'messages', o.QUOTES.length, 'quotes');
