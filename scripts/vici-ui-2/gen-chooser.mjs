// Generates src/content/sosChooserArt.ts: the two cards' drawings on
// `97 · SOS — Urge or Relapse` (`Vici UI 2/project/Email Login.dc.html`), as drawn.
//
//   node scripts/vici-ui-2/gen-chooser.mjs
import fs from 'node:fs';
import { unPaintOrder } from './svg.mjs';

const html = fs.readFileSync('Vici UI 2/project/Email Login.dc.html', 'utf8');
const at = html.indexOf('data-screen-label="SOS Chooser"');
const frame = html.slice(at, html.indexOf('<dc-import name="Vici Relapse"', at));
const svgs = [...frame.matchAll(/<svg width="100%" height="100%" viewBox="([^"]*)"[^>]*>([\s\S]*?)<\/svg>/g)];
if (svgs.length !== 2) throw new Error(`expected two drawings, found ${svgs.length}`);
const [urge, relapse] = svgs.map((m) => ({ viewBox: m[1], markup: unPaintOrder(m[2]) }));
fs.writeFileSync(
  'src/content/sosChooserArt.ts',
  `// Generated by scripts/vici-ui-2/gen-chooser.mjs from \`Vici UI 2/project/Email Login.dc.html\` (\`97 · SOS — Urge or Relapse\`). Do not edit by hand.\n\n` +
    `export const SOS_CHOOSER_ART = {\n  urge: ${JSON.stringify(urge)},\n  relapse: ${JSON.stringify(relapse)},\n} as const;\n`,
);
console.log('two drawings');
