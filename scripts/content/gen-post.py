# Regenerate src/content/morningNotes.ts and viciLetters.ts from the owner's two documents.
#   textutil -convert txt -output DIR/morning.txt Vici_Morning_Notifications.docx
#   textutil -convert txt -output DIR/emails.txt Vici_Milestone_and_Relapse_Emails.docx
#   python3 scripts/content/gen-post.py DIR src/content
import re, json, sys
D = sys.argv[1]; OUT = sys.argv[2]
curly = lambda s: s.replace("'", "’")
js = lambda s: json.dumps(curly(s), ensure_ascii=False)
AUTHORS = ['Marcus Aurelius', 'Seneca']
def split_quote(t):
    for a in AUTHORS:
        m = re.match(r'^(“[^”]+”\s*—\s*' + a + r')\s+(.+)$', t)
        if m: return m.group(1) + '\n' + m.group(2)
    return t

# ── morning notes
lines = [l.strip() for l in open(f'{D}/morning.txt', encoding='utf-8')]
days = {}
rel = {}
for l in lines:
    m = re.match(r'^Day (\d+)\s+(.+)$', l)
    if m: days[int(m.group(1))] = split_quote(m.group(2)); continue
    m = re.match(r'^Relapse (\d+)\s+(.+)$', l)
    if m: rel[int(m.group(1))] = split_quote(m.group(2))
assert sorted(days) == list(range(1, 85)), sorted(set(range(1,85)) - set(days))
assert sorted(rel) == list(range(1, 26))
WHEN = {9: 'repeated', 11: 'tired', 14: 'stress'}
out = ['/**',
 ' * The morning notifications, in the owner\'s words (`Vici_Morning_Notifications.docx`):',
 ' * one for each of the 84 mornings, and 25 for the morning after a reported slip.',
 ' * `[user name]` is filled in, or left out with the words around it, by `fillName`',
 ' * (src/lib/viciPost.ts). A quote and the line after it are split by a line break.',
 ' * Generated by scripts/content/gen-post.py from the document; edit the document and regenerate, or edit here.',
 ' */', '',
 '/** Day 1 to day 84, in order. */',
 'export const MORNING_NOTES: readonly string[] = [']
for d in range(1, 85): out.append(f'  {js(days[d])},')
out += ['];', '',
 '/** When a relapse note may be used: only when it matches what the user reported (the document\'s rule). */',
 "export type RelapseNoteWhen = 'tired' | 'stress' | 'repeated';", '',
 '/** The 25 notes for the morning after a slip, in the document\'s order (Relapse 1 to 25). */',
 'export const RELAPSE_NOTES: readonly { text: string; when?: RelapseNoteWhen }[] = [']
for r in range(1, 26):
    w = f", when: '{WHEN[r]}'" if r in WHEN else ''
    out.append(f'  {{ text: {js(rel[r])}{w} }},')
out += ['];', '']
open(f'{OUT}/morningNotes.ts', 'w', encoding='utf-8').write('\n'.join(out))

# ── letters
txt = open(f'{D}/emails.txt', encoding='utf-8').read().split('\n')
letters = []; cur = None; mode = None
for raw in txt:
    l = raw.strip()
    if not l: continue
    m = re.match(r'^([MR]\d\d) (.+)$', l)
    if m and not l.startswith('Marcus'):
        cur = {'id': m.group(1), 'name': m.group(2), 'paras': []}; letters.append(cur); continue
    if cur is None: continue
    if l.startswith('Send when'): cur['when'] = l[len('Send when'):].strip(); continue
    if l.startswith('Subject'): cur['subject'] = l[len('Subject'):].strip(); continue
    if 'greeting' not in cur:
        g = re.match(r'^(Hi|Hello|Good morning|Morning) \[user name\],$', l)
        assert g, (cur['id'], l)
        cur['greeting'] = g.group(1); continue
    if l == 'Vici': cur['done'] = True; cur_done = cur; cur = None; continue
    cur['paras'].append(l)
ids = [x['id'] for x in letters]
assert ids == [f'M{i:02d}' for i in range(1, 26)] + [f'R{i:02d}' for i in range(1, 26)], ids
for x in letters: assert x.get('done') and x.get('subject') and x['paras'], x['id']
def block(name, xs):
    o = [f'export const {name}: readonly ViciLetter[] = [']
    for x in xs:
        o.append(f"  {{\n    id: '{x['id']}',\n    name: {js(x['name'])},\n    sendWhen: {js(x['when'])},\n    subject: {js(x['subject'])},\n    greeting: '{x['greeting']}',\n    paragraphs: [")
        for p in x['paras']: o.append(f'      {js(p)},')
        o.append('    ],\n  },')
    o.append('];')
    return o
out = ['/**',
 ' * VICI\'s letters, in the owner\'s words (`Vici_Milestone_and_Relapse_Emails.docx`): 25 for',
 ' * milestones and 25 for the morning after a reported slip. They arrive in the app, over Today,',
 ' * and stay in Mail (src/lib/viciPost.ts decides which and when). `[user name]` is filled in,',
 ' * or left out with the words around it, by `fillName`. Every letter is signed "Vici".',
 ' * Generated by scripts/content/gen-post.py from the document; edit the document and regenerate, or edit here.',
 ' */', '',
 "export type LetterGreeting = 'Hi' | 'Hello' | 'Good morning' | 'Morning';", '',
 'export type ViciLetter = {',
 "  /** `M01`–`M25` milestones, `R01`–`R25` after a slip */",
 '  id: string;',
 '  /** the document\'s own name for it */',
 '  name: string;',
 '  /** the document\'s delivery note */',
 '  sendWhen: string;',
 '  subject: string;',
 '  greeting: LetterGreeting;',
 '  paragraphs: readonly string[];',
 '};', '']
out += block('MILESTONE_LETTERS', [x for x in letters if x['id'][0] == 'M']) + ['']
out += block('RELAPSE_LETTERS', [x for x in letters if x['id'][0] == 'R']) + ['']
out += ['/** Every letter by its id. */',
 'export const LETTER_BY_ID: Readonly<Record<string, ViciLetter>> = Object.fromEntries([...MILESTONE_LETTERS, ...RELAPSE_LETTERS].map((l) => [l.id, l]));', '']
open(f'{OUT}/viciLetters.ts', 'w', encoding='utf-8').write('\n'.join(out))
print('ok', len(days), len(rel), len(letters))
