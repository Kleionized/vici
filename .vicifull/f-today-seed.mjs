#!/usr/bin/env node
/**
 * GROUP today — write the group's capture accounts as `--initseed` files.
 *
 * Pass 1 seeded through `.vicifull/todayshot.mjs`, which builds the account in
 * node and injects it. `scripts/vicifull/audit.mjs` cannot run that: it only
 * knows `shot.mjs` and its `--initseed=<file.js>`, so the group's seven recipes
 * were being replayed **unseeded** — /today with no signed-in mock user, which
 * is not the screen any of them describes (FINDINGS F27). This emits the same
 * accounts as plain browser scripts so the recipes are executable by the
 * runner rather than only by hand.
 *
 * The account is dated relative to the day it is READ, not the day it is
 * written: every timestamp is emitted as an offset from that build's midnight
 * and re-based in the page, so a file written today still draws "Day 41" a
 * fortnight from now. `.vicifull/seed.json` went stale exactly this way.
 *
 *   node .vicifull/f-today-seed.mjs
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

const DAY = 86_400_000;
const buildMidnight = new Date().setHours(0, 0, 0, 0);
const seed = JSON.parse(execFileSync('node', ['scripts/uifinal1/seed.mjs'], { encoding: 'utf8', maxBuffer: 64 << 20 }));

/**
 * `21 · Today` prints "▲ 18" beside the number, which is `buildScore`'s delta:
 * 4 for the clean day, 2 for this morning's check-in and 2 per urge ridden
 * today — so the frame's own account rode six out today. The generator spreads
 * its twenty-four urges evenly and lands one on today, giving 8. Six are moved
 * onto today here, which leaves every total the score is built from untouched
 * (same count, same types) and lets the arrow row be read at the width the
 * canvas draws it.
 */
seed.events.filter((e) => e.type === 'urge_rode_out').slice(0, 6).forEach((e, i) => { e.createdAt = buildMidnight + (14 + i) * 3600e3; });

/**
 * `21 · Today — p3` signs the pledge card `Jerry`, and so do five more frames
 * across the bundle (`Your Vow Page`, `Morning Pledge Signed`, `Relapse
 * Resign`, `Slip Pledge`, `Urge Hub — Pledges`). `Marcus` — the name the seed
 * generator carries — is printed on **no frame in the drop**, so the seed's own
 * name was the only reason that row could not be compared (FINDINGS F28, and
 * the same call DECISIONS D097 made for the `day` group's seed).
 */
const NAME = 'Jerry';
seed.user.displayName = NAME;

const UID = 'today-seed-user';
seed.user.clerkUserId = UID;
seed.lifeMap.userId = UID;
for (const e of seed.events) e.userId = UID;
for (const k of Object.keys(seed.checkins)) seed.checkins[k].userId = UID;
for (const k of Object.keys(seed.progress)) seed.progress[k].userId = UID;
for (const j of seed.journalEntries) j.userId = UID;

/** Every absolute ms in the tree, as an offset from this build's midnight. */
function relativise(node) {
  if (Array.isArray(node)) return node.map(relativise);
  if (node && typeof node === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      out[k] = typeof v === 'number' && v > 1e12 ? { __at: v - buildMidnight } : relativise(v);
    }
    return out;
  }
  return node;
}

const body = (dayOverride) => `/* GENERATED by .vicifull/f-today-seed.mjs — GROUP today's capture account.
   Do not hand-edit; re-run the generator. */
(() => {
  const UID = ${JSON.stringify(UID)};
  const DAY = 86400000;
  const M = new Date().setHours(0, 0, 0, 0);
  const key = (ms) => { const d = new Date(ms); return \`\${d.getFullYear()}-\${String(d.getMonth() + 1).padStart(2, '0')}-\${String(d.getDate()).padStart(2, '0')}\`; };
  const rebase = (n) => Array.isArray(n) ? n.map(rebase)
    : (n && typeof n === 'object') ? (Object.prototype.hasOwnProperty.call(n, '__at') ? M + n.__at : Object.fromEntries(Object.entries(n).map(([k, v]) => [k, rebase(v)])))
    : n;
  const data = rebase(${JSON.stringify(relativise(seed))});
  /* the check-ins are keyed and dated by LOCAL calendar day, so they are
     re-keyed off the rebased timestamps rather than carried as literals */
  const checkins = {};
  const days = Object.keys(data.checkins).length;
  Object.values(data.checkins).forEach((c, i) => {
    const k = key(M - (days - 1 - i) * DAY);
    checkins[k] = { ...c, date: k };
  });
  data.checkins = checkins;
${dayOverride ? `  /* --day=${dayOverride}: move the account's opening so Today counts ${dayOverride} days */
  data.user.createdAt = M - ${dayOverride - 1} * DAY;\n` : ''}  localStorage.setItem('tideline.mock.users', JSON.stringify({ 'seed@vici.app': { userId: UID, email: 'seed@vici.app', password: 'x', displayName: ${JSON.stringify(NAME)} } }));
  localStorage.setItem('tideline.session.userId', UID);
  localStorage.setItem('tideline.mock.userdata.' + UID, JSON.stringify(data));
  /* Two one-shot gates in src/app/(app)/_layout.tsx push a route over /today on
     first launch — the weekly report ("Your weekly report is ready.") and the
     check-in prompt. Pass 1 dismissed the first with a timed tap on "Later" and
     never met the second, because the report gate returns before it. At a low
     day count no week has closed, the report gate does not fire, and the
     check-in prompt takes the screen instead — which is why a day-1 or day-5
     capture landed on /day/morning. Both are marked seen here so the capture
     lands on the screen it asked for at any day. */
  const mon = (t) => { const x = new Date(t); x.setHours(0, 0, 0, 0); x.setDate(x.getDate() - ((x.getDay() + 6) % 7)); return x; };
  localStorage.setItem('tideline.weeklyReport.seenWeek', JSON.stringify(key(mon(M).getTime() - 7 * DAY)));
  localStorage.setItem('tideline.checkinPromptAt', JSON.stringify(Date.now()));
})();
`;

for (const [file, day] of [['today-seed.js', 0], ['today-seed-d86.js', 86], ['today-seed-d5.js', 5]]) {
  fs.writeFileSync('.vicifull/' + file, body(day));
  console.log('.vicifull/' + file + (day ? ` (day ${day})` : ' (day 41, the seed generator\'s own)'));
}
